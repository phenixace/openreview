const HAN_PATTERN = /\p{Script=Han}/u;
const HAN_GLOBAL_PATTERN = /\p{Script=Han}+/gu;
const TRANSLATION_LOOKUP = {
  ...MACHINE_TRANSLATIONS,
  ...MANUAL_TRANSLATIONS,
};
const TRANSLATION_ENTRIES = Object.entries(TRANSLATION_LOOKUP).sort(
  ([left], [right]) => right.length - left.length,
);

export function containsChinese(value) {
  return typeof value === "string" && HAN_PATTERN.test(value);
}

export function translateToEnglish(value) {
  if (typeof value !== "string" || !containsChinese(value)) return value;

  const leadingSpace = /^\s/.test(value) ? " " : "";
  const trailingSpace = /\s$/.test(value) ? " " : "";
  let translated = value.trim();
  const exactTranslation = TRANSLATION_LOOKUP[translated];
  if (exactTranslation) {
    return `${leadingSpace}${exactTranslation}${trailingSpace}`;
  }
  for (const [pattern, replacement] of DYNAMIC_TRANSLATIONS) {
    translated = translated.replace(pattern, replacement);
  }
  for (const [source, replacement] of TRANSLATION_ENTRIES) {
    if (translated.includes(source)) {
      translated = translated.split(source).join(replacement);
    }
  }

  const cleaned = translated
    .replaceAll("，", ", ")
    .replaceAll("。", ".")
    .replaceAll("；", "; ")
    .replaceAll("：", ": ")
    .replaceAll("（", " (")
    .replaceAll("）", ")")
    .replaceAll("「", "“")
    .replaceAll("」", "”")
    .replaceAll("『", "“")
    .replaceAll("』", "”")
    .replace(HAN_GLOBAL_PATTERN, "academic-system text")
    .replace(/\.{2,}/g, ".")
    .replace(/\s+([,.;:!?])/g, "$1")
    .replace(/ {2,}/g, " ")
    .trim();

  return `${leadingSpace}${cleaned}${trailingSpace}`;
}
